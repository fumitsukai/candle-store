export const dynamic = "force-dynamic"; // ← ensure no layout caching

import type { Metadata } from "next";
import {
  Crimson_Text,
  Plus_Jakarta_Sans,
  Poppins,
  DM_Serif_Display,
} from "next/font/google";
import "./globals.css";
import MainNav from "@/components/main-nav";
import Footer from "@/components/footer";
import { CartProvider } from "@/contexts/CartContext";
import { createClient } from "@/utils/supabase/server";
import SessionProvider from "@/components/session_provider";

const tenor = DM_Serif_Display({
  subsets: ["latin"],
  weight: ["400"],
  variable: "--font-tenor",
});
const workSans = Plus_Jakarta_Sans({
  subsets: ["latin"],
  variable: "--font-work-sans",
});
const poppins = Poppins({
  subsets: ["latin"],
  weight: ["300", "400", "500"],
  variable: "--font-poppins",
});

export const metadata: Metadata = {
  title: "Candle Store",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const supabase = createClient();
  const {
    data: { user },
    error,
  } = await supabase.auth.getUser();

  if (error) {
    console.log("Failed to fetch user: ", user);
  }
  return (
    <html
      lang="en"
      className={`${tenor.variable} ${workSans.variable} ${poppins.variable}`}
    >
      <body className="font-body bg-lightkeeper-lightgray text-lightkeeper-charcoal">
        <SessionProvider initialUser={user}>
          <CartProvider>
            <div className="flex flex-col min-h-screen text-sm">
              <MainNav />
              <div className="space-y-4 flex-1">{children}</div>
              <Footer />
            </div>
          </CartProvider>
        </SessionProvider>
      </body>
    </html>
  );
}
